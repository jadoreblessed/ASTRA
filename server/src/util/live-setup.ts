import { randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

/**
 * One-time setup for live mode (real money, tiny limits): writes `.env.live`
 * with fresh secrets and its own database, so the dev database and its public
 * dev key never hold a lamport. Run once; `npm run dev:live` then uses it.
 * Refuses to overwrite an existing file — that file's MASTER_KEY is the vault.
 */

const file = join(dirname(fileURLToPath(import.meta.url)), "..", "..", ".env.live");

if (existsSync(file)) {
  console.log(`.env.live already exists — keeping it (its MASTER_KEY opens the vault).\n${file}`);
  process.exit(0);
}

writeFileSync(
  file,
  `# ASTRA live mode — real money, tiny limits. Generated by \`npm run live:setup\`.
# MASTER_KEY opens the vault and every email wallet: keep a copy somewhere safe
# (a password manager), never commit this file, never paste it anywhere.
MASTER_KEY=${randomBytes(32).toString("base64")}
SIGNER_TOKEN=${randomBytes(32).toString("hex")}

# Its own database, apart from the dev one.
PGLITE_DIR=./.data/live

TRADING_ENABLED=true
# Lifetime cap on what the platform pays itself (fees + rent): 0.05 SOL.
MAX_TOTAL_SPEND_LAMPORTS=50000000
MAX_ORDER_USD=2
MAX_SLIPPAGE_BPS=100
PRICE_MAX_AGE_SEC=120

# The public RPC works but drops transactions under load. A free Helius key
# (https://www.helius.dev) lands swaps far more reliably:
# SOLANA_RPC_URL=https://mainnet.helius-rpc.com/?api-key=YOUR_KEY
SOLANA_RPC_URL=https://api.mainnet-beta.solana.com
`,
  { mode: 0o600 },
);

console.log(`Wrote ${file}

Next:
  1. Back up the MASTER_KEY line from that file (password manager).
  2. npm run dev:live
  3. Open http://localhost:8080/api/config — "vault" is the address to fund.
     Send it 0.04 SOL for fees and rent. Nothing else goes there by hand.`);
